class JobTests(unittest.TestCase):
    def test_progress_eta_only_with_total(self):
        t = [0.0]
        j = jobs.Job('x', clock=lambda: t[0], sleep=lambda s: None)
        j.start_phase('p', None, 'paths')
        t[0] = 1.0
        j.advance(10)
        s = j.snapshot()
        self.assertIsNone(s['percent'])
        self.assertIsNone(s['eta_s'])
        j.start_phase('q', 100, 'bytes')
        t[0] = 2.0
        j.advance(25)
        t[0] = 3.0
        j.advance(25)
        s = j.snapshot()
        self.assertEqual(s['percent'], 50.0)
        self.assertEqual(s['eta_s'], 2)

    def test_cancel_and_pause(self):
        j = jobs.Job('x', sleep=lambda s: None)
        j.cancel()
        with self.assertRaises(jobs.Cancelled):
            j.checkpoint()
        j2 = jobs.Job('y', sleep=lambda s: None)
        j2.pause()
        threading.Timer(0.2, j2.resume).start()
        t0 = time.monotonic()
        j2.checkpoint()
        self.assertGreaterEqual(time.monotonic() - t0, 0.15)

    def test_quiet_mode_throttles(self):
        slept = []
        t = [0.0]
        j = jobs.Job('x', 'quiet', clock=lambda: t[0], sleep=slept.append)
        j.advance(1, nbytes=80 * 1024 * 1024)
        self.assertTrue(any(s >= 0.9 for s in slept), slept)
        f = jobs.Job('x', 'fast', clock=lambda: t[0], sleep=slept.clear)
        f.advance(1, nbytes=80 * 1024 * 1024)


class StoreTests(Tmp):
    def test_atomic_json_and_damaged_file(self):
        p = self.tmp / 'a.json'
        store.atomic_write_json(p, {'x': 'ü'})
        self.assertEqual(store.read_json(p), {'x': 'ü'})
        self.assertFalse(p.with_name('a.json.partial').exists())
        p.write_text('{not json')
        with self.assertRaises(store.StoreError):
            store.read_json(p)

    def test_instance_lock_excludes_second_holder(self):
        lock = self.tmp / 'l.lock'
        with store.instance_lock(lock):
            if os.name != 'nt':
                import subprocess
                code = ('import sys; sys.path.insert(0, %r)\nfrom v3lab import store\n'
                        'try:\n  store.instance_lock(%r).__enter__(); print("got")\nexcept store.StoreError: print("busy")') % (str(ROOT / 'tools'), str(lock))
                out = subprocess.run([sys.executable, '-c', code], capture_output=True, text=True).stdout.strip()
                self.assertEqual(out, 'busy')
        with store.instance_lock(lock):
            pass

    def test_verified_copy_publishes_only_complete_matching_copies(self):
        src = self.tmp / 'src.bin'
        src.write_bytes(b'abc' * 1000)
        dest = self.tmp / 'out' / 'dst.bin'
        dest.parent.mkdir()
        d = store.verified_copy(lambda: open(src, 'rb'), dest, 3000, hashlib.sha256(b'abc' * 1000).hexdigest())
        self.assertEqual(dest.read_bytes(), b'abc' * 1000)
        self.assertEqual(d, hashlib.sha256(b'abc' * 1000).hexdigest())
        with self.assertRaises(store.StoreError):
            store.verified_copy(lambda: open(src, 'rb'), self.tmp / 'bad.bin', 3000, '0' * 64)
        self.assertFalse((self.tmp / 'bad.bin').exists())
        self.assertFalse((self.tmp / 'bad.bin.partial').exists())

    def test_card_removed_mid_copy(self):
        class Dying(io.BytesIO):
            def read(self, n=-1):
                if self.tell() > 2000:
                    raise OSError(22, 'The device is not ready')
                return super().read(min(n, 1000))
        with self.assertRaises(OSError):
            store.verified_copy(lambda: Dying(b'x' * 5000), self.tmp / 'c.bin', 5000)
        self.assertFalse((self.tmp / 'c.bin').exists())
        self.assertFalse((self.tmp / 'c.bin.partial').exists())

    def test_short_source_and_changed_source(self):
        with self.assertRaises(store.StoreError):
            store.verified_copy(lambda: io.BytesIO(b'x' * 10), self.tmp / 'd.bin', 20)
        n = [0]

        def stamp():
            n[0] += 1
            return n[0]
        with self.assertRaises(store.StoreError):
            store.verified_copy(lambda: io.BytesIO(b'x' * 10), self.tmp / 'e.bin', 10, stamp=stamp)

    def test_insufficient_space(self):
        with mock.patch('shutil.disk_usage', return_value=mock.Mock(free=10)):
            with self.assertRaises(store.StoreError) as cm:
                store.require_space(self.tmp, 1000, 'the thing')
            self.assertIn('not enough free space', str(cm.exception))


