@unittest.skipUnless(HAVE_EXT, 'dissect.extfs not installed')
class RootfsTests(Tmp):
    def m(self, name):
        return lf.manifest(lf.container(name), name)

    def policy(self):
        return rootfs.load_policy(ROOT)

    def test_pristine_against_itself(self):
        r = rootfs.compare(self.m('pristine'), self.m('pristine'), self.policy(), 'prepared')
        self.assertEqual(r['verdict'], 'REVIEW')   # expected first-boot changes did not happen
        self.assertEqual(r['counts']['fail'], 0)

    def test_legitimate_first_boot(self):
        r = rootfs.compare(self.m('pristine'), self.m('prepared'), self.policy(), 'prepared')
        self.assertEqual(r['verdict'], 'PASS', rootfs.summarize(r))
        rules = sorted(i['rule'] for i in r['items'])
        self.assertEqual(rules, ['dir-link-count', 'dropbear-symlink-to-directory', 'run-initctl-fifo', 'run-utmp-boot-record'])

    def test_capture_boot_against_prepared_baseline(self):
        r = rootfs.compare(self.m('prepared'), self.m('postcapture'), self.policy(), 'post-capture')
        self.assertEqual(r['verdict'], 'PASS', rootfs.summarize(r))
        self.assertEqual([i['rule'] for i in r['items']], ['run-utmp-rewritten-each-boot'])

    def test_first_boot_changes_are_not_accepted_after_capture(self):
        # Post-capture compares with the prepared baseline: a pristine baseline would show the
        # first-boot changes as unexplained, which is the point of keeping the baseline.
        r = rootfs.compare(self.m('pristine'), self.m('postcapture'), self.policy(), 'post-capture')
        self.assertEqual(r['verdict'], 'FAIL')

    def test_tampering_fails_closed_with_reasons(self):
        r = rootfs.compare(self.m('pristine'), self.m('tampered'), self.policy(), 'prepared')
        self.assertEqual(r['verdict'], 'FAIL')
        text = ' '.join(rootfs.summarize(r))
        self.assertIn('/etc/init.d/S99evil', text)
        self.assertIn('executable', text)
        self.assertIn('/etc/inittab', text)
        self.assertIn('perm', text)
        self.assertIn('/etc/hostname', text)                 # extended attribute added
        self.assertIn('/usr/lib/libfixture-hardlink.so.1', text)  # removed hard link

    def test_orphans_and_unclean_state_need_review(self):
        r = rootfs.compare(self.m('pristine'), self.m('orphan'), self.policy(), 'prepared')
        self.assertEqual(r['verdict'], 'REVIEW')
        self.assertTrue(any('orphan' in x for x in r['health']['review']))

    def test_records_cover_every_type(self):
        m = self.m('pristine')
        types = {r['type'] for r in m.entries.values()}
        self.assertTrue({'dir', 'file', 'symlink', 'fifo', 'chardev'} <= types)
        self.assertEqual(m.entries['/dev/console']['device'], [5, 1])
        self.assertEqual(m.hardlink_groups(), [['/usr/lib/libfixture-hardlink.so.1', '/usr/lib/libfixture.so.1']])
        self.assertTrue(any(x[0] == 'user.fixture' for x in m.entries['/usr/lib/libfixture.so.1']['xattrs']))
        self.assertNotIn('inode', json.dumps(m.entries))

    def test_policy_rule_violations(self):
        base, cur = self.m('pristine'), self.m('prepared')
        cur.entries['/run/initctl'] = dict(cur.entries['/run/initctl'], perm='0666')
        r = rootfs.compare(base, cur, self.policy(), 'prepared')
        self.assertEqual(r['verdict'], 'FAIL')
        cur = self.m('prepared')
        cur.entries['/run/utmp'] = dict(cur.entries['/run/utmp'], size=385)
        self.assertEqual(rootfs.compare(base, cur, self.policy(), 'prepared')['verdict'], 'FAIL')
        cur = self.m('prepared')
        cur.entries['/etc/dropbear/dropbear_rsa_host_key'] = dict(type='file', perm='0600', uid=0, gid=0, flags='0x0',
                                                                  storage_flags='0x80000', links=1, xattrs=[], size=1, sha256='0' * 64)
        self.assertEqual(rootfs.compare(base, cur, self.policy(), 'prepared')['verdict'], 'FAIL')
        cur = self.m('prepared')
        cur.entries['/etc'] = dict(cur.entries['/etc'], links=cur.entries['/etc']['links'] + 1)   # unexplained link count
        self.assertEqual(rootfs.compare(base, cur, self.policy(), 'prepared')['verdict'], 'FAIL')
        cur = self.m('prepared')
        cur.entries['/bin/busybox'] = dict(cur.entries['/bin/busybox'], uid=1000)
        r = rootfs.compare(base, cur, self.policy(), 'prepared')
        self.assertTrue(any(i.get('sensitive') for i in r['items'] if i['status'] == 'fail'))

    def test_interrupted_scan_resumes_to_identical_result(self):
        from dissect.extfs import ExtFS
        data = lf.container('pristine')
        sha = lf.sha(data)
        fresh = lf.manifest(data, 'fresh')
        db = self.tmp / 'ck.sqlite'
        with self.assertRaises(KeyboardInterrupt):
            rootfs.scan(ExtFS(io.BytesIO(data)), sha, db, interrupt_after=7)
        resumed = rootfs.scan(ExtFS(io.BytesIO(data)), sha, db)
        self.assertEqual(resumed.digest(), fresh.digest())
        self.assertEqual(rootfs.scan(ExtFS(io.BytesIO(data)), sha, db).digest(), fresh.digest())  # completed reuse

    def test_completed_checkpoint_digest_detects_altered_record(self):
        from dissect.extfs import ExtFS
        import sqlite3
        data = lf.container('pristine')
        db = self.tmp / 'ck.sqlite'
        rootfs.scan(ExtFS(io.BytesIO(data)), lf.sha(data), db)
        # sqlite3.Connection's context manager commits/rolls back but does not
        # close the file handle. Windows cannot unlink an open database.
        from contextlib import closing
        with closing(sqlite3.connect(db)) as conn, conn:
            cursor = conn.execute("UPDATE entries SET rec = ? WHERE path = '/etc/inittab'", (json.dumps({'type':'file','sha256':'0'*64}),))
            self.assertEqual(cursor.rowcount, 1)
            cursor.close()
        with self.assertRaisesRegex(rootfs.RootfsError, 'damaged digest'):
            rootfs.scan(ExtFS(io.BytesIO(data)), lf.sha(data), db)
        # Assert both the test and production code released the database, even
        # on the corruption error path (especially important on Windows).
        db.unlink()
        self.assertFalse(db.exists())

    def test_checkpoint_of_other_input_is_refused(self):
        from dissect.extfs import ExtFS
        data = lf.container('pristine')
        db = self.tmp / 'ck.sqlite'
        rootfs.scan(ExtFS(io.BytesIO(data)), lf.sha(data), db)
        with self.assertRaises(rootfs.RootfsError):
            rootfs.scan(ExtFS(io.BytesIO(data)), '9' * 64, db)

    def test_corrupt_checkpoint_database(self):
        from dissect.extfs import ExtFS
        import sqlite3
        data = lf.container('pristine')
        db = self.tmp / 'ck.sqlite'
        db.write_bytes(b'this is not a database' * 100)
        with self.assertRaises(sqlite3.DatabaseError):
            rootfs.scan(ExtFS(io.BytesIO(data)), lf.sha(data), db)

    def test_unsupported_features_fail_closed(self):
        from dissect.extfs import ExtFS
        data = bytearray(lf.container('pristine'))
        # s_feature_ro_compat lives at superblock offset 0x64 (superblock starts at byte 1024).
        off = 1024 + 0x64
