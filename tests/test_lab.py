class FakeResponse(io.BytesIO):
    def __init__(self, data, status=200):
        super().__init__(data)
        self.status = status

    def getcode(self):
        return self.status

    def __enter__(self):
        return self

    def __exit__(self, *a):
        self.close()


class DownloadTests(Tmp):
    DATA = os.urandom(3 * 1024 * 1024 + 17)

    def opener(self, fail_after=None, honour_range=True, data=None):
        data = data if data is not None else self.DATA
        calls = []

        def op(req, timeout=60):
            rng = req.headers.get('Range')
            calls.append(rng)
            start = int(rng.split('=')[1].rstrip('-')) if (rng and honour_range) else 0
            body = data[start:]
            if fail_after is not None and len(calls) == 1:
                body = body[:fail_after]
                class Broken(FakeResponse):
                    def read(self, n=-1):
                        b = super().read(n)
                        if not b:
                            raise ConnectionResetError('connection reset')
                        return b
                return Broken(body, 206 if start else 200)
            return FakeResponse(body, 206 if (start and honour_range) else 200)
        op.calls = calls
        return op

    def test_interrupted_download_resumes_with_range(self):
        dest = self.tmp / 'fw.img.gz'
        sha = hashlib.sha256(self.DATA).hexdigest()
        op = self.opener(fail_after=1024 * 1024)
        with self.assertRaises(ConnectionResetError):
            download.download('https://x/fw', dest, len(self.DATA), sha, opener=op)
        self.assertTrue(dest.with_name(dest.name + '.partial').exists())
        r = download.download('https://x/fw', dest, len(self.DATA), sha, opener=op)
        self.assertEqual(r['status'], 'downloaded')
        self.assertEqual(op.calls[-1], 'bytes=1048576-')
        self.assertEqual(dest.read_bytes(), self.DATA)
        self.assertEqual(download.download('https://x/fw', dest, len(self.DATA), sha, opener=op)['status'], 'reused')

    def test_server_ignoring_range_restarts_cleanly(self):
        dest = self.tmp / 'fw.bin'
        sha = hashlib.sha256(self.DATA).hexdigest()
        dest.with_name(dest.name + '.partial').write_bytes(self.DATA[:1000])
        store.atomic_write_json(Path(str(dest) + '.partial.json'), dict(url='https://x/fw', size=len(self.DATA), sha256=sha))
        download.download('https://x/fw', dest, len(self.DATA), sha, opener=self.opener(honour_range=False))
        self.assertEqual(dest.read_bytes(), self.DATA)

    def test_wrong_hash_and_wrong_size_and_stale_partial(self):
        dest = self.tmp / 'fw.bin'
        with self.assertRaises(store.StoreError):
            download.download('https://x/fw', dest, len(self.DATA), '0' * 64, opener=self.opener())
        self.assertFalse(dest.exists())
        with self.assertRaises(store.StoreError):
            download.download('https://x/fw', dest, len(self.DATA) - 5, '0' * 64, opener=self.opener())
        part = dest.with_name(dest.name + '.partial')
        part.write_bytes(b'from another file')
        store.atomic_write_json(Path(str(part) + '.json'), dict(url='https://other', size=1, sha256='3' * 64))
        sha = hashlib.sha256(self.DATA).hexdigest()
        op = self.opener()
        download.download('https://x/fw', dest, len(self.DATA), sha, opener=op)
        self.assertIsNone(op.calls[-1])  # the stale partial was discarded, not resumed

    def test_corrupted_final_file_is_replaced(self):
        dest = self.tmp / 'fw.bin'
        sha = hashlib.sha256(self.DATA).hexdigest()
        download.download('https://x/fw', dest, len(self.DATA), sha, opener=self.opener())
        with open(dest, 'r+b') as f:
            f.write(b'X')
        self.assertFalse(download.is_verified(dest, len(self.DATA), sha))
        download.download('https://x/fw', dest, len(self.DATA), sha, opener=self.opener())
        self.assertEqual(dest.read_bytes(), self.DATA)

    def test_expand_gzip_checks_size_and_hash(self):
        raw = b'image bytes ' * 50000
        gz = self.tmp / 'a.gz'
        gz.write_bytes(gzip.compress(raw))
        out = self.tmp / 'a.img'
        j = jobs.Job('e', 'fast')
        download.expand_gzip(gz, out, len(raw), hashlib.sha256(raw).hexdigest(), j)
        self.assertEqual(out.read_bytes(), raw)
        self.assertIsNotNone(j.snapshot()['percent'])
        with self.assertRaises(store.StoreError):
            download.expand_gzip(gz, self.tmp / 'b.img', len(raw) - 1, hashlib.sha256(raw).hexdigest())
        self.assertFalse((self.tmp / 'b.img').exists())
        (self.tmp / 'bad.gz').write_bytes(b'not gzip at all')
        with self.assertRaises(Exception):
            download.expand_gzip(self.tmp / 'bad.gz', self.tmp / 'c.img', 10, '0' * 64)
        self.assertFalse((self.tmp / 'c.img.partial').exists())

    def test_interrupted_expansion_leaves_no_output(self):
        raw = os.urandom(5 * 1024 * 1024)
        gz = self.tmp / 'a.gz'
        gz.write_bytes(gzip.compress(raw))
        j = jobs.Job('e', 'fast')
        orig = j.advance

        def adv(*a, **k):
            orig(*a, **k)
            if j.done > 1024 * 1024:
                j.cancel()
        j.advance = adv
        with self.assertRaises(jobs.Cancelled):
            download.expand_gzip(gz, self.tmp / 'x.img', len(raw), hashlib.sha256(raw).hexdigest(), j)
        self.assertFalse((self.tmp / 'x.img').exists())
        self.assertFalse((self.tmp / 'x.img.partial').exists())


